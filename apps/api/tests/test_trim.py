def test_storage_rejects_path_traversal_ids(test_context: APIContext) -> None:
    # Direct unit check: the validator must reject anything non-hex.
    import pytest

    storage = test_context.storage
    for bad_id in ("..", "../etc/passwd", "abc/../def", "hello!", ""):
        with pytest.raises(FileNotFoundError):
            storage.analysis_paths(bad_id)


def test_trim_applies_all_cuts_by_default(
    client: TestClient, test_context: APIContext
) -> None:
    analysis_id = _upload_and_analyze(client)
    payload = test_context.storage.read_analysis_payload(analysis_id)
    default_cut_count = len([cut for cut in payload.cutPlan if cut.defaultSelected])
    if not default_cut_count:
        # The stubbed fixtures should produce at least one deadspace range.
        # If they don't, the test is not meaningful, so skip gracefully.
        import pytest

        pytest.skip("No default-selected cuts generated by the stub fixture.")

    response = client.post(f"/api/analysis/{analysis_id}/trim", json={})
    assert response.status_code == 200
    body = response.json()
    assert body["analysisId"] == analysis_id
    assert body["trimmedVideoUrl"].startswith("/storage/")
    assert body["originalDurationSec"] == payload.video.durationSec
    assert body["removedSeconds"] >= 0
    assert body["trimmedDurationSec"] <= body["originalDurationSec"]
    assert len(body["appliedCuts"]) == default_cut_count

    # Subsequent fetches should surface the trimmed URL in artifacts.
    refreshed = client.get(f"/api/analysis/{analysis_id}").json()
    assert refreshed["payload"]["artifacts"]["trimmedVideoUrl"] == body["trimmedVideoUrl"]
    assert refreshed["payload"]["diagnostics"]["trimmedDurationSec"] == body["trimmedDurationSec"]
    assert refreshed["payload"]["exports"]


