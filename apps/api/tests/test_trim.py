# -----------------------------
# Unit tests for MediaService._invert_cuts
# These exercise the pure deadspace-inversion logic without touching ffmpeg.
# -----------------------------


def test_invert_cuts_single_middle_cut() -> None:
    keep = MediaService._invert_cuts([(2.0, 4.0)], total_duration_sec=10.0)
    assert keep == [(0.0, 2.0), (4.0, 10.0)]


def test_invert_cuts_leading_cut() -> None:
    keep = MediaService._invert_cuts([(0.0, 3.0)], total_duration_sec=10.0)
    assert keep == [(3.0, 10.0)]


def test_invert_cuts_trailing_cut() -> None:
    keep = MediaService._invert_cuts([(7.5, 10.0)], total_duration_sec=10.0)
    assert keep == [(0.0, 7.5)]


def test_invert_cuts_merges_overlaps() -> None:
    keep = MediaService._invert_cuts(
        [(1.0, 3.0), (2.5, 5.0)], total_duration_sec=10.0
    )
    assert keep == [(0.0, 1.0), (5.0, 10.0)]


def test_invert_cuts_drops_ranges_under_hundred_ms() -> None:
    # A 90ms cut is below the 100ms threshold and should be dropped.
    keep = MediaService._invert_cuts([(1.0, 1.09)], total_duration_sec=5.0)
    assert keep == [(0.0, 5.0)]


def test_invert_cuts_keeps_exact_hundred_ms_range() -> None:
    keep = MediaService._invert_cuts([(1.0, 1.1)], total_duration_sec=5.0)
    assert keep == [(0.0, 1.0), (1.1, 5.0)]


def test_invert_cuts_clamps_out_of_bounds() -> None:
    # Negative start and past-end ranges should be clamped in-bounds.
    keep = MediaService._invert_cuts(
        [(-5.0, 2.0), (8.0, 99.0)], total_duration_sec=10.0
    )
    assert keep == [(2.0, 8.0)]


def test_invert_cuts_full_clip_removed() -> None:
    # A cut covering the full clip should produce no keep ranges.
    keep = MediaService._invert_cuts([(0.0, 10.0)], total_duration_sec=10.0)
    assert keep == []


def test_invert_cuts_rejects_zero_duration() -> None:
    keep = MediaService._invert_cuts([(0.0, 1.0)], total_duration_sec=0.0)
    assert keep == []


def test_invert_cuts_sorts_unordered_input() -> None:
    keep = MediaService._invert_cuts(
        [(6.0, 7.0), (1.0, 2.0)], total_duration_sec=10.0
    )
    assert keep == [(0.0, 1.0), (2.0, 6.0), (7.0, 10.0)]


# -----------------------------
# API-level tests for the trim endpoint
# These use the StubMediaService from conftest so ffmpeg never runs.
# -----------------------------


def _upload_and_analyze(client: TestClient) -> str:
    upload = client.post(
        "/api/upload",
        files={"file": ("clip.mp4", BytesIO(b"fake-mp4"), "video/mp4")},
    ).json()
    analysis = client.post(
        "/api/analyze", json={"uploadId": upload["uploadId"]}
    ).json()
    # The immediate job service runs synchronously, so the record should be completed.
    loaded = client.get(f"/api/analysis/{analysis['analysisId']}").json()
    assert loaded["status"] == "completed"
    return analysis["analysisId"]


