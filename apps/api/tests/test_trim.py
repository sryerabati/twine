def test_trim_accepts_cut_ids_and_persists_export_metadata(
    client: TestClient, test_context: APIContext
) -> None:
    analysis_id = _upload_and_analyze(client)
    payload = test_context.storage.read_analysis_payload(analysis_id)
    if not payload.cutPlan:
        import pytest

        pytest.skip("No cut plan generated by the stub fixture.")

    selected = payload.cutPlan[:2]
    response = client.post(
        f"/api/analysis/{analysis_id}/trim",
        json={"cutIds": [cut.id for cut in selected]},
    )
    assert response.status_code == 200
    body = response.json()
    assert [cut["id"] for cut in body["appliedCuts"]] == [cut.id for cut in selected]

    refreshed = test_context.storage.read_analysis_payload(analysis_id)
    assert refreshed.exports
    assert refreshed.exports[-1].selectedCutIds == [cut.id for cut in selected]
